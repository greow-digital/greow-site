export const aiGrowthByLang = { en: aiGrowth, sv: aiGrowthSv }
export const aiGrowthMetaByLang = { en: aiGrowthMeta, sv: aiGrowthMetaSv }

// Page-level JSON-LD (Service + FAQPage + BreadcrumbList). The site graph with
// #organization / #erik comes from the root layout.
export function aiGrowthJsonLd(lang: 'en' | 'sv') {
  const SITE_URL = 'https://greow.digital'
  const c = aiGrowthByLang[lang]
  const meta = aiGrowthMetaByLang[lang]
  const url = `${SITE_URL}${meta.path}`
  const sv = lang === 'sv'
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'Service',
        '@id': `${url}#service`,
        name: sv ? 'AI-tillväxtkonsultation' : 'AI Growth Consulting',
        serviceType: sv ? 'AI-tillväxtkonsult' : 'AI growth consulting',
        description: meta.description,
        url,
        inLanguage: lang,
        provider: { '@id': `${SITE_URL}/#organization` },
        areaServed: sv ? ['Sverige', 'Skandinavien', 'Europa'] : ['Sweden', 'Scandinavia', 'Europe'],
        hasOfferCatalog: {
          '@type': 'OfferCatalog',
          name: c.hero.kicker,
          itemListElement: c.whatIDo.items.map((item) => ({
            '@type': 'Offer',
            itemOffered: { '@type': 'Service', name: item.title, description: item.tagline },
          })),
        },
      },
      {
        '@type': 'FAQPage',
        '@id': `${url}#faq`,
        inLanguage: lang,
        mainEntity: c.faq.items.map((item) => ({
          '@type': 'Question',
          name: item.q,
          acceptedAnswer: { '@type': 'Answer', text: item.a.join(' ') },
        })),
      },
      {
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'Greow', item: sv ? `${SITE_URL}/sv/` : `${SITE_URL}/` },
          { '@type': 'ListItem', position: 2, name: sv ? 'AI-tillväxtkonsult' : 'AI Growth Consultant', item: url },
        ],
      },
    ],
  }
}
